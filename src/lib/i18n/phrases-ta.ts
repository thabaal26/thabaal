/** The Tamil for a fixed English phrase, or undefined when there isn't one. */
export function phraseTa(s: string): string | undefined {
  return PHRASES_TA[s.trim()];
}

/** English or its Tamil, keeping the leading/trailing spaces of the original. */
export function trText(s: string, ta: boolean): string {
  if (!ta) return s;
  const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(s);
  const hit = m && PHRASES_TA[m[2]];
  return hit ? `${m[1]}${hit}${m[3]}` : s;
}

/**
 * Translates the plain-text parts of a label (a string, or a list like `[<Icon />, " Save"]`)
 * and leaves everything else (icons, names, numbers) as it is.
 */
export function trNode(node: ReactNode, ta: boolean): ReactNode {
  if (!ta) return node;
  if (typeof node === "string") return trText(node, true);
  if (Array.isArray(node)) return Children.map(node, (n) => trNode(n as ReactNode, true));
  if (isValidElement(node) && node.type === Fragment) {
    const el = node as ReactElement<{ children?: ReactNode }>;
    return cloneElement(el, undefined, trNode(el.props.children, true));
  }
  return node;
}
