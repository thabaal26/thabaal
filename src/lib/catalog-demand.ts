import "server-only";
import { db } from "./db";
import type { CatalogProductDetail } from "./catalog";

export type ProductDemandStats = {
  retailerId: string;
  name: string;
  imageUrl: string | null;
  priceAmount: number;
  category: string;
  inStock: boolean;
  whatsappStatus?: "APPROVED" | "PENDING" | "REJECTED" | "OUTDATED" | null;
  /** Total WhatsApp carts where a customer added this product */
  cartCount: number;
  /** Total units requested (litres, packets, bottles) across carts */
  unitsDemanded: number;
  /** Number of paid / completed orders containing this product */
  paidOrdersCount: number;
  /** Units actually purchased and paid for */
  paidUnits: number;
  /** Total revenue generated by this product */
  revenue: number;
  /** Cart to paid order conversion rate % */
  conversionRate: number;
  /** Number of carts where product was added but not completed/paid */
  hesitationCount: number;
  /** Popularity percentage relative to the #1 most carted item (0 - 100%) for progress bar */
  demandIndex: number;
  /** Leaderboard rank (1 = most popular) */
  rank: number;
  /** Last time this product was added to a cart */
  lastCartedAt: Date | null;
};

export type CatalogDemandSummary = {
  totalCartsAnalyzed: number;
  totalUnitsDemanded: number;
  totalCatalogRevenue: number;
  topDemanded: { name: string; retailerId: string; carts: number; units: number } | null;
  topRevenue: { name: string; retailerId: string; revenue: number } | null;
  topConverting: { name: string; retailerId: string; rate: number; paidCount: number } | null;
  topHesitation: { name: string; retailerId: string; hesitationCount: number } | null;
  products: ProductDemandStats[];
  /** Map of SKU -> ProductDemandStats for fast lookup */
  demandBySku: Record<string, ProductDemandStats>;
};

type RawOrderItem = {
  id?: string;
  name?: string;
  quantity?: number | string;
  price?: number | string;
  currency?: string;
};

const norm = (s: string | null | undefined) => (s ?? "").trim().toLowerCase();

/**
 * Aggregates live customer demand, cart frequency, units requested, and checkout conversion
 * for all catalogue products from real WhatsApp orders and carts.
 */
export async function getCatalogDemandSummary(
  clientId: string,
  catalogProducts: CatalogProductDetail[],
): Promise<CatalogDemandSummary> {
  const orders = await db.order.findMany({
    where: { clientId },
    select: {
      id: true,
      number: true, ref: true,
      status: true,
      paidAt: true,
      total: true,
      items: true,
      createdAt: true,
    },
    orderBy: { createdAt: "desc" },
  });

  const totalCartsAnalyzed = orders.length;

  // SKU -> aggregated metrics
  type ItemAccumulator = {
    cartCount: number;
    unitsDemanded: number;
    paidOrdersCount: number;
    paidUnits: number;
    revenue: number;
    hesitationCount: number;
    lastCartedAt: Date | null;
    sampleName: string;
    samplePrice: number;
  };

  const skuMap = new Map<string, ItemAccumulator>();
  const nameToSku = new Map<string, string>();

  // Initialize skuMap with catalog products
  for (const p of catalogProducts) {
    const key = p.retailerId.trim();
    skuMap.set(key, {
      cartCount: 0,
      unitsDemanded: 0,
      paidOrdersCount: 0,
      paidUnits: 0,
      revenue: 0,
      hesitationCount: 0,
      lastCartedAt: null,
      sampleName: p.name,
      samplePrice: p.priceAmount,
    });
    if (p.name) {
      nameToSku.set(norm(p.name), key);
    }
  }

  let totalCatalogRevenue = 0;
  let totalUnitsDemanded = 0;

  for (const o of orders) {
    const items = (Array.isArray(o.items) ? o.items : []) as RawOrderItem[];
    const isPaid =
      o.paidAt !== null ||
      o.status === "PAID" ||
      o.status === "DISPATCHED" ||
      o.status === "DELIVERED";

    for (const it of items) {
      const rawId = (it.id ?? "").trim();
      const rawName = (it.name ?? "").trim();
      const qty = Math.max(1, Number(it.quantity) || 1);
      const price = Number(it.price) || 0;

      // Match by exact SKU first, then by normalized product name
      let matchedSku = rawId && skuMap.has(rawId) ? rawId : null;
      if (!matchedSku && rawName) {
        matchedSku = nameToSku.get(norm(rawName)) ?? null;
      }
      const targetSku = matchedSku || rawId || (rawName ? `ITEM-${norm(rawName).slice(0, 8)}` : "UNKNOWN");

      let acc = skuMap.get(targetSku);
      if (!acc) {
        acc = {
          cartCount: 0,
          unitsDemanded: 0,
          paidOrdersCount: 0,
          paidUnits: 0,
          revenue: 0,
          hesitationCount: 0,
          lastCartedAt: null,
          sampleName: rawName || targetSku,
          samplePrice: price,
        };
        skuMap.set(targetSku, acc);
      }

      acc.cartCount += 1;
      acc.unitsDemanded += qty;
      totalUnitsDemanded += qty;

      if (!acc.lastCartedAt || o.createdAt > acc.lastCartedAt) {
        acc.lastCartedAt = o.createdAt;
      }

      if (isPaid) {
        acc.paidOrdersCount += 1;
        acc.paidUnits += qty;
        const lineRev = price * qty;
        acc.revenue += lineRev;
        totalCatalogRevenue += lineRev;
      } else {
        acc.hesitationCount += 1;
      }
    }
  }

  // Build the list of ProductDemandStats
  const catalogBySku = new Map<string, CatalogProductDetail>();
  for (const p of catalogProducts) {
    catalogBySku.set(p.retailerId.trim(), p);
  }

  const allProductStats: ProductDemandStats[] = [];

  for (const [sku, acc] of skuMap.entries()) {
    const catProd = catalogBySku.get(sku);
    const conversionRate = acc.cartCount > 0 ? Math.round((acc.paidOrdersCount / acc.cartCount) * 100) : 0;

    allProductStats.push({
      retailerId: sku,
      name: catProd?.name || acc.sampleName || sku,
      imageUrl: catProd?.imageUrl ?? null,
      priceAmount: catProd?.priceAmount ?? acc.samplePrice ?? 0,
      category: catProd?.category || "General",
      inStock: catProd?.inStock ?? true,
      whatsappStatus: catProd?.whatsappStatus ?? null,
      cartCount: acc.cartCount,
      unitsDemanded: acc.unitsDemanded,
      paidOrdersCount: acc.paidOrdersCount,
      paidUnits: acc.paidUnits,
      revenue: acc.revenue,
      conversionRate,
      hesitationCount: acc.hesitationCount,
      demandIndex: 0, // filled below
      rank: 0, // filled below
      lastCartedAt: acc.lastCartedAt,
    });
  }

  // Sort by popularity:
  // 1. Highest cartCount first
  // 2. Highest unitsDemanded
  // 3. Highest revenue
  // 4. Alphabetical name
  allProductStats.sort((a, b) => {
    if (b.cartCount !== a.cartCount) return b.cartCount - a.cartCount;
    if (b.unitsDemanded !== a.unitsDemanded) return b.unitsDemanded - a.unitsDemanded;
    if (b.revenue !== a.revenue) return b.revenue - a.revenue;
    return a.name.localeCompare(b.name);
  });

  const maxCarts = allProductStats[0]?.cartCount || 1;

  const demandBySku: Record<string, ProductDemandStats> = {};

  allProductStats.forEach((p, idx) => {
    p.rank = idx + 1;
    p.demandIndex = Math.round((p.cartCount / maxCarts) * 100);
    demandBySku[p.retailerId] = p;
  });

  // Top Highlights
  const topDemandedItem = allProductStats.find((p) => p.cartCount > 0);
  const topDemanded = topDemandedItem
    ? { name: topDemandedItem.name, retailerId: topDemandedItem.retailerId, carts: topDemandedItem.cartCount, units: topDemandedItem.unitsDemanded }
    : null;

  const revenueSorted = [...allProductStats].sort((a, b) => b.revenue - a.revenue);
  const topRevItem = revenueSorted.find((p) => p.revenue > 0);
  const topRevenue = topRevItem
    ? { name: topRevItem.name, retailerId: topRevItem.retailerId, revenue: topRevItem.revenue }
    : null;

  // Best converting with at least 2 carts
  const convertingSorted = [...allProductStats]
    .filter((p) => p.cartCount >= 2)
    .sort((a, b) => b.conversionRate - a.conversionRate || b.paidOrdersCount - a.paidOrdersCount);
  const topConvItem = convertingSorted[0] || allProductStats.find((p) => p.paidOrdersCount > 0);
  const topConverting = topConvItem
    ? { name: topConvItem.name, retailerId: topConvItem.retailerId, rate: topConvItem.conversionRate, paidCount: topConvItem.paidOrdersCount }
    : null;

  // Top hesitation: item with high carts but low conversion (dropped carts)
  const hesitationSorted = [...allProductStats]
    .filter((p) => p.cartCount >= 2 && p.conversionRate <= 30)
    .sort((a, b) => b.hesitationCount - a.hesitationCount);
  const topHesItem = hesitationSorted[0] || allProductStats.find((p) => p.hesitationCount > 0);
  const topHesitation = topHesItem
    ? { name: topHesItem.name, retailerId: topHesItem.retailerId, hesitationCount: topHesItem.hesitationCount }
    : null;

  return {
    totalCartsAnalyzed,
    totalUnitsDemanded,
    totalCatalogRevenue,
    topDemanded,
    topRevenue,
    topConverting,
    topHesitation,
    products: allProductStats,
    demandBySku,
  };
}
