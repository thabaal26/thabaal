const { execSync } = require('child_process');

const remoteScript = `
const https = require('https');
const fs = require('fs');

const envContent = fs.readFileSync('/srv/thabaal/shared/.env', 'utf8');
let keyId = '';
for (const line of envContent.split('\\n')) {
  if (line.startsWith('RAZORPAY_KEY_ID=')) keyId = line.split('=')[1].replace(/^["']|["']$/g, '').trim();
}

function rzpGetMethods() {
  return new Promise((resolve, reject) => {
    const auth = Buffer.from(keyId + ':').toString('base64');
    const req = https.request({
      hostname: 'api.razorpay.com',
      port: 443,
      path: '/v1/methods',
      method: 'GET',
      headers: {
        'Authorization': 'Basic ' + auth,
        'Content-Type': 'application/json'
      }
    }, res => {
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => {
        try { resolve(JSON.parse(data)); } catch(e) { resolve(data); }
      });
    });
    req.on('error', reject);
    req.end();
  });
}

rzpGetMethods().then(res => {
  console.log('--- RAZORPAY METHODS FOR MERCHANT ACCOUNT ---');
  console.log(JSON.stringify(res, null, 2));
}).catch(console.error);
`;

